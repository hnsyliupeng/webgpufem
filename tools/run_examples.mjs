// tools/run_examples.mjs — headless runner: build each example, solve statics/dynamics,
// verify against analytic references, render a screenshot PNG, and write reports.
// usage: node tools/run_examples.mjs [--shots-only] [exId]
import { EXAMPLES, getExample } from '../examples/index.js';
import { computeStatics, runDynamics } from '../core/solvers.js';
import { describeScene } from '../core/render_scene.js';
import { renderPNG, savePNG } from './raster.mjs';
import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'fs';

const args = process.argv.slice(2);
const shotsOnly = args.includes('--shots-only');
const onlyId = args.find(a => !a.startsWith('--'));

const results = [];

for (const ex of EXAMPLES) {
  if (onlyId && ex.id !== onlyId) continue;
  console.log(`\n=== ${ex.id} ${ex.name} ===`);
  const t0 = Date.now();
  const model = ex.build();
  // statics
  const st = computeStatics(model, { tol: 1e-7, maxIter: 80 });
  const staticTension = model.lines[0] ? model.lines[0].segT[0] : null;
  const staticReaction = model.lines[0] ? Math.hypot(...model.lines[0].reactionA) : null;
  const staticHeave = model.bodies[0] ? model.bodies[0].q[2] : 0;
  console.log(`statics: residual=${st.residual.toExponential(2)} iters=${st.iterations} converged=${st.converged}`);
  let run = null;
  if (!shotsOnly && ex.analysis.kind === 'dynamics') {
    if (ex.perturb) ex.perturb(model);
    run = runDynamics(model, {
      tEnd: ex.analysis.tEnd, staticsFirst: false, init: false,
      sampleDt: 0.05, snapDt: ex.analysis.snapDt ?? 0.5, safety: 0.25,
    });
    console.log(`dynamics: steps=${run.steps} dt=${run.dt.toExponential(2)} tEnd=${run.tEnd}s samples=${run.series.t.length}`);
  }
  const ctx = { st, run, staticTension, staticReaction, staticHeave, model };
  let checks = [];
  if (!shotsOnly) {
    checks = ex.verify(model, ctx);
    for (const c of checks) {
      const pass = c.pass !== undefined ? c.pass : Math.abs(c.actual - c.expected) <= c.tol * Math.max(Math.abs(c.expected), c.absFloor ?? 0.01);
      c.pass = pass;
      console.log(`  [${pass ? 'PASS' : 'FAIL'}] ${c.name}: expected=${fmt(c.expected)} actual=${fmt(c.actual)} ${c.unit || ''}`);
    }
  }
  // screenshot
  let snap = null;
  if (run && run.snapshots.length) snap = run.snapshots[Math.floor(run.snapshots.length * 0.6)];
  const sceneDesc = describeScene(model, snap, { camera: ex.camera, waveGridN: ex.id === 'ex10' ? 28 : 18 });
  if (model.env.waves) sceneDesc.waterGetEta = (x, y, t) => model.env.waves.eta(x, y, t);
  const img = renderPNG(sceneDesc, { width: 1280, height: 800 });
  const shotPath = `screenshots/${ex.id}.png`;
  savePNG(img, shotPath);
  console.log(`screenshot -> ${shotPath}`);
  results.push({
    id: ex.id, name: ex.name, cat: ex.cat, desc: ex.desc,
    statics: { residual: st.residual, iterations: st.iterations, converged: st.converged },
    dynamics: run ? { steps: run.steps, dt: run.dt, tEnd: run.tEnd, samples: run.series.t.length } : null,
    checks, extra: ctx.extra || null,
    shot: shotPath, ms: Date.now() - t0,
    pass: checks.length ? checks.every(c => c.pass) : true,
  });
}

function fmt(v) { return typeof v === 'number' ? (Math.abs(v) > 1e6 || (Math.abs(v) < 1e-3 && v !== 0) ? v.toExponential(3) : v.toFixed(4)) : v; }

mkdirSync('docs', { recursive: true });
mkdirSync('app', { recursive: true });
// merge with previous results so a single-example run doesn't wipe the other entries
let prev = [];
try {
  if (existsSync('app/verification_data.js')) {
    const s = readFileSync('app/verification_data.js', 'utf8');
    prev = JSON.parse(s.slice(s.indexOf('{'), s.lastIndexOf('}') + 1)).results || [];
  }
} catch {}
const merged = [...prev.filter(r => !results.some(x => x.id === r.id)), ...results];
const allPass = merged.every(r => r.pass);

// JSON for the app
const appData = {
  generated: new Date().toISOString(),
  allPass,
  partial: !!onlyId,
  rerun: onlyId || null,
  results: merged.map(r => ({ ...r, checks: r.checks.map(c => ({ ...c })) })),
};
writeFileSync('app/verification_data.js', `// auto-generated by tools/run_examples.mjs — do not edit\nexport const VERIFICATION = ${JSON.stringify(appData, null, 1)};\n`);

// markdown report
let md = `# 算例验证报告 (auto-generated)\n\n生成时间: ${appData.generated}${appData.partial ? `（本次仅重跑 ${appData.rerun}，其余沿用已有结果）` : ''}\n\n总体: **${allPass ? '全部 PASS' : '存在 FAIL'}**\n\n| 算例 | 名称 | 静力残差 | 动力步数 | 结果 |\n|---|---|---|---|---|\n`;
for (const r of merged) {
  md += `| ${r.id} | ${r.name} | ${r.statics.residual.toExponential(1)} | ${r.dynamics ? r.dynamics.steps : '-'} | ${r.pass ? '✅ PASS' : '❌ FAIL'} |\n`;
}
md += `\n## 详细校核项\n\n`;
for (const r of merged) {
  md += `### ${r.id} ${r.name}\n\n${r.desc}\n\n`;
  md += `| 校核项 | 期望 | 实际 | 单位 | 容差 | 结果 |\n|---|---|---|---|---|---|\n`;
  for (const c of r.checks) {
    md += `| ${c.name} | ${fmt(c.expected)} | ${fmt(c.actual)} | ${c.unit || ''} | ${fmt(c.tol)} | ${c.pass ? 'PASS' : 'FAIL'} |\n`;
  }
  if (r.extra) md += `\n附加: \`\`\`json\n${JSON.stringify(r.extra)}\n\`\`\`\n`;
  md += `\n截图: ![${r.id}](screenshots/${r.id}.png)\n\n`;
}
writeFileSync('docs/verification_report.md', md);

// html report
let html = `<!doctype html><meta charset="utf-8"><title>验证报告</title><style>body{font-family:sans-serif;margin:2em;background:#0e1420;color:#dde}table{border-collapse:collapse;margin:1em 0}td,th{border:1px solid #345;padding:4px 8px;font-size:13px}.pass{color:#4c4}.fail{color:#f66}img{max-width:640px;border:1px solid #345}</style><h1>算例验证报告</h1><p>生成时间 ${appData.generated} — 总体 <b>${allPass ? '全部 PASS' : '存在 FAIL'}</b></p>`;
for (const r of merged) {
  html += `<h2>${r.id} ${r.name}</h2><p>${r.desc}</p><img src="../${r.shot}"><table><tr><th>校核项</th><th>期望</th><th>实际</th><th>单位</th><th>结果</th></tr>`;
  for (const c of r.checks) html += `<tr><td>${c.name}</td><td>${fmt(c.expected)}</td><td>${fmt(c.actual)}</td><td>${c.unit || ''}</td><td class="${c.pass ? 'pass' : 'fail'}">${c.pass ? 'PASS' : 'FAIL'}</td></tr>`;
  html += `</table>`;
}
writeFileSync('docs/verification_report.html', html);

console.log(`\n===== ${allPass ? 'ALL PASS' : 'SOME FAILED'} =====`);
for (const r of results) console.log(`${r.pass ? 'PASS' : 'FAIL'} ${r.id} ${r.name} (${r.ms} ms, ${r.checks.filter(c => c.pass).length}/${r.checks.length})`);
process.exit(allPass ? 0 : 1);
